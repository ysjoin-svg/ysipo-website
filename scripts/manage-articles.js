const fs = require('fs');
const path = require('path');
const readline = require('readline');
const { execSync } = require('child_process');

const WEBSITE_DIR = path.resolve(__dirname, '..');
const INSIGHTS_DIR = path.join(WEBSITE_DIR, 'insights');
const ARTICLES_JSON = path.join(INSIGHTS_DIR, 'articles.json');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

function ask(question) {
  return new Promise(resolve => rl.question(question, resolve));
}

async function main() {
  if (!fs.existsSync(ARTICLES_JSON)) {
    console.log('❌ 找不到 articles.json，請先執行 generate-article.js');
    rl.close();
    return;
  }

  const articles = JSON.parse(fs.readFileSync(ARTICLES_JSON, 'utf8'));

  console.log('\n=== 文章管理工具 ===\n');
  console.log('目前文章清單：\n');

  articles.forEach((article, i) => {
    const auto = article.autoGenerated ? '[自動]' : '[手動]';
    console.log(`${i + 1}. ${auto} ${article.title}`);
    console.log(`   分類：${article.category} | 日期：${article.date}`);
    console.log(`   檔案：${article.filename}\n`);
  });

  const action = await ask('選擇動作 (d=刪除 / e=編輯標題 / q=離開): ');

  if (action === 'q') {
    rl.close();
    return;
  }

  const numStr = await ask('輸入文章編號: ');
  const num = parseInt(numStr) - 1;
  if (isNaN(num) || num < 0 || num >= articles.length) {
    console.log('❌ 編號無效');
    rl.close();
    return;
  }

  const target = articles[num];

  if (action === 'd') {
    const confirm = await ask(`確定要刪除「${target.title}」？(y/n): `);
    if (confirm.toLowerCase() === 'y') {
      const filePath = path.join(INSIGHTS_DIR, target.filename);
      if (fs.existsSync(filePath)) {
        fs.unlinkSync(filePath);
        console.log(`🗑️  已刪除：${target.filename}`);
      }

      articles.splice(num, 1);
      fs.writeFileSync(ARTICLES_JSON, JSON.stringify(articles, null, 2), 'utf8');

      try {
        execSync(`git -C "${WEBSITE_DIR}" add -A`, { stdio: 'inherit' });
        execSync(`git -C "${WEBSITE_DIR}" commit -m "delete: ${target.title}"`, { stdio: 'inherit' });
        execSync(`git -C "${WEBSITE_DIR}" push origin master`, { stdio: 'inherit' });
        console.log('✅ 文章已刪除並推送到 GitHub');
      } catch (e) {
        console.log('⚠️  Git 推送失敗：', e.message);
      }
    } else {
      console.log('已取消');
    }

  } else if (action === 'e') {
    const newTitle = await ask(`新標題（目前：${target.title}）: `);
    if (newTitle.trim()) {
      const filePath = path.join(INSIGHTS_DIR, target.filename);
      if (fs.existsSync(filePath)) {
        let html = fs.readFileSync(filePath, 'utf8');
        html = html.replace(/<title>.*?<\/title>/, `<title>${newTitle} | 永旭智慧財產事務所</title>`);
        html = html.replace(/<h1 class="article-title">.*?<\/h1>/, `<h1 class="article-title">${newTitle}</h1>`);
        fs.writeFileSync(filePath, html, 'utf8');
      }

      target.title = newTitle;
      fs.writeFileSync(ARTICLES_JSON, JSON.stringify(articles, null, 2), 'utf8');

      try {
        execSync(`git -C "${WEBSITE_DIR}" add -A`, { stdio: 'inherit' });
        execSync(`git -C "${WEBSITE_DIR}" commit -m "edit: 修改文章標題 - ${newTitle}"`, { stdio: 'inherit' });
        execSync(`git -C "${WEBSITE_DIR}" push origin master`, { stdio: 'inherit' });
        console.log('✅ 標題已更新並推送');
      } catch (e) {
        console.log('⚠️  Git 推送失敗：', e.message);
      }
    } else {
      console.log('已取消（標題未變更）');
    }
  }

  rl.close();
}

main().catch(err => {
  console.error('❌ 錯誤：', err.message);
  rl.close();
  process.exit(1);
});
