const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { textToHtml, textToHtmlEn, extractSummary, categorizeArticle, purgeCloudflareCache } = require('./generate-article');

const ROOT = path.resolve(__dirname, '..');
const REVIEW_URL = process.env.REVIEW_BASE_URL || 'https://review.ysipo.com.tw';
const KEY = process.env.REVIEW_INGEST_KEY;
const esc = (value) => String(value ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

function git(...args) { execFileSync('git', ['-C', ROOT, ...args], { stdio: 'inherit' }); }

function publishArticle(draft) {
  const c = draft.content;
  const now = new Date();
  const date = now.toISOString().slice(0, 10);
  const stamp = now.getTime();
  const zhFile = `article-${date}-${stamp}.html`;
  const enFile = `article-${date}-${stamp}-en.html`;
  const imgFile = `article-${date}-${stamp}.jpg`;
  const category = categorizeArticle(c.category);
  const img = Buffer.from(c.imageBase64, 'base64');
  if (img.length < 1000 || !/^[a-zA-Z0-9+/=]+$/.test(c.imageBase64)) throw new Error('封面圖內容無效');
  fs.mkdirSync(path.join(ROOT, 'insights', 'img'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'insights', 'img', imgFile), img);
  const imgPath = `img/${imgFile}`;
  const width = Number(c.imageWidth);
  const height = Number(c.imageHeight);
  if (!width || !height || Math.abs(width / height - 16 / 9) > 0.01) throw new Error('封面圖比例不是 16:9');
  const bodyZh = esc(c.bodyZh);
  const bodyEn = esc(c.bodyEn);
  fs.writeFileSync(path.join(ROOT, 'insights', zhFile), textToHtml(bodyZh, esc(c.titleZh), date, category, imgPath, width, height, zhFile, enFile), 'utf8');
  fs.writeFileSync(path.join(ROOT, 'insights', enFile), textToHtmlEn(bodyEn, esc(c.titleEn), date, category, imgPath, width, height, zhFile, enFile), 'utf8');
  execFileSync('node', [path.join(__dirname, 'check-article-layout.js')], { stdio: 'inherit' });
  const indexPath = path.join(ROOT, 'insights', 'articles.json');
  const articles = JSON.parse(fs.readFileSync(indexPath, 'utf8'));
  articles.unshift({
    filename: zhFile, filenameEn: enFile, title: esc(c.titleZh), titleEn: esc(c.titleEn),
    category: category.name, categorySlug: category.slug, image: `insights/img/${imgFile}`,
    date, readTime: '5', summary: esc(extractSummary(c.bodyZh)), summaryEn: esc(extractSummary(c.bodyEn)),
    autoGenerated: true, reviewed: true, createdAt: now.toISOString(),
  });
  fs.writeFileSync(indexPath, JSON.stringify(articles, null, 2), 'utf8');
  git('add', `insights/${zhFile}`, `insights/${enFile}`, `insights/img/${imgFile}`, 'insights/articles.json');
  git('commit', '-m', `publish: reviewed article ${date}`);
  git('push', 'origin', 'master');
  return `https://ysipo.com.tw/insights/${zhFile}`;
}

function publishNews(draft) {
  const c = draft.content;
  const indexPath = path.join(ROOT, 'scripts', 'published-news.json');
  const published = JSON.parse(fs.readFileSync(indexPath, 'utf8'));
  if (published.some((item) => item.link === c.link)) throw new Error('此新聞已經發布');
  const date = new Date(c.date);
  if (Number.isNaN(date.getTime())) throw new Error('新聞日期無效');
  const months = ['JAN','FEB','MAR','APR','MAY','JUN','JUL','AUG','SEP','OCT','NOV','DEC'];
  const card = `\n            <article class="news-item">\n              <div class="news-date"><div class="day">${String(date.getDate()).padStart(2, '0')}</div><div class="month-year">${months[date.getMonth()]} ${date.getFullYear()}</div></div>\n              <div class="news-content"><h3><a href="${esc(c.link)}" target="_blank" rel="noopener" style="color:inherit;">${esc(c.title)}</a></h3><p>${esc(c.summary)}</p><div style="margin-top: var(--space-2);"><span class="tag tag--outline">智財新聞</span><span style="font-size:var(--text-xs);color:var(--color-text-muted);margin-left:var(--space-2);">資料來源：${esc(c.source === 'moea.gov.tw' || c.source === 'tipo.gov.tw' ? '經濟部智慧財產局' : c.source)}</span></div></div>\n            </article>\n`;
  const htmlPath = path.join(ROOT, 'news.html');
  let html = fs.readFileSync(htmlPath, 'utf8');
  const marker = '<div class="news-list" data-source="ai-agent">';
  const index = html.indexOf(marker);
  if (index < 0) throw new Error('找不到新聞插入點');
  const at = index + marker.length;
  html = html.slice(0, at) + card + html.slice(at);
  fs.writeFileSync(htmlPath, html, 'utf8');
  published.unshift({ origTitle: c.origTitle || c.title, displayTitle: c.title, source: c.source, date: c.date, link: c.link, addedAt: new Date().toISOString() });
  fs.writeFileSync(indexPath, JSON.stringify(published, null, 2), 'utf8');
  const oldPendingPath = path.join(ROOT, 'scripts', 'pending-news.json');
  const oldPending = JSON.parse(fs.readFileSync(oldPendingPath, 'utf8'));
  fs.writeFileSync(oldPendingPath, JSON.stringify(oldPending.filter((item) => item.link !== c.link), null, 2), 'utf8');
  git('add', 'news.html', 'scripts/published-news.json', 'scripts/pending-news.json');
  git('commit', '-m', `publish: reviewed news ${draft.id.slice(0, 8)}`);
  git('push', 'origin', 'master');
  return 'https://ysipo.com.tw/news.html';
}

async function request(endpoint, options = {}) {
  const response = await fetch(`${REVIEW_URL}${endpoint}`, { ...options, headers: { Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json', ...(options.headers || {}) } });
  if (!response.ok) throw new Error(`審稿服務 HTTP ${response.status}`);
  return response;
}

async function main() {
  const id = process.argv[2];
  if (!KEY || !/^[a-f0-9]{32}$/.test(id || '')) throw new Error('缺少合法草稿 ID 或 REVIEW_INGEST_KEY');
  let status = 'failure';
  let url;
  try {
    const draft = await (await request(`/api/drafts/${id}`)).json();
    url = draft.type === 'article' ? publishArticle(draft) : publishNews(draft);
    status = 'success';
    await new Promise((resolve) => setTimeout(resolve, 60000));
    try { await purgeCloudflareCache(); }
    catch (error) { console.warn(`已發布，但清快取失敗：${error.message}`); }
  } finally {
    await request(`/api/drafts/${id}/result`, { method: 'POST', body: JSON.stringify({ status, url }) });
  }
  console.log(`已發布：${url}`);
}

if (require.main === module) main().catch((error) => { console.error(error); process.exit(1); });
module.exports = { publishArticle, publishNews };
